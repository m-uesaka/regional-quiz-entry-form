-- 大会のエントリー受付を一時中断できるようにする。統括スタッフと、その大会を
-- 担当する地域スタッフが `PUT /api/staff/tournaments/:tournamentId/entry-pause`
-- から切り替える。
--
-- 中断中は、エントリー期間内でも新しいエントリー(匿名・ログイン済みとも)を
-- 受け付けず、フォームは担当スタッフにしか開けない(期間外と同じ扱い)。
-- ポータルには「一時中断中」と出る。すでにあるエントリーの編集・キャンセル・
-- 確認リンクでの確定は止めない: 中断は新しい受付を止めるためのもので、
-- すでに申し込んだ人の手続きまで止めると、確認リンクの期限切れで申し込みが
-- 失効してしまうため。
--
-- 期間とは独立した状態として持つ(期間を書き換えて止めると、再開のときに
-- 元の締切を覚えておく必要があり、ポータルにも「受付終了」と出てしまう)。
alter table tournaments
  add column entries_paused boolean not null default false;
