-- 同じリリースの Worker から呼ばなくなるが(判定はトリガの繰り返しだった)、
-- マイグレーションは Worker より先に走るので、デプロイ中の古い Worker が
-- まだ呼ぶ。`participants.region_id` の廃止(#309)と合わせて消す。
